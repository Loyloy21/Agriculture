-- AgriReach: farmer production (harvest) records and the commodity list they reference.
-- BACKWARD COMPATIBLE:
--   * New table public.commodities: the crop / commodity reference list (name + agricultural category).
--     No such list existed before (farm_profiles.main_product is free text), so production records need it
--     for a stable commodity ID. Rows are reference data the office can later extend or set Inactive.
--   * New table public.production_records: one row per harvest a farmer submits from the mobile app, in
--     kilograms, linked to the farmer, the farm (when applicable) and the commodity. Monthly totals are
--     calculated from harvest_date at read time; nothing is pre-aggregated, so nothing can be counted twice.
--     status starts as 'Submitted'; 'Rejected' rows are kept but not counted.
-- Nothing is dropped and no existing row is rewritten.
--
-- Apply with:   php scripts/pgsql-migrate.php --connection=supabase
-- Roll back:    database/pgsql/rollback/20261023_0006_production_records.down.sql

BEGIN;

CREATE TABLE public.commodities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    agricultural_category varchar(100) NOT NULL,
    status varchar(8) NOT NULL DEFAULT 'Active',
    created_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    updated_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    CONSTRAINT uq_commodities_category_name UNIQUE (agricultural_category, name),
    CONSTRAINT chk_commodities_category CHECK (agricultural_category IN ('Crops', 'Livestock', 'Poultry', 'Fishpond')),
    CONSTRAINT chk_commodities_status CHECK (status IN ('Active', 'Inactive'))
);
CREATE TRIGGER trg_commodities_updated_at BEFORE UPDATE ON public.commodities FOR EACH ROW EXECUTE FUNCTION public.agrireach_touch_updated_at();

