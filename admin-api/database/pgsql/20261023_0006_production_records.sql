CREATE TABLE public.production_records (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id integer NOT NULL,
    farm_profile_id integer,
    commodity_id integer NOT NULL,
    harvest_date date NOT NULL,
    quantity_kg numeric(12,2) NOT NULL,
    remarks varchar(1000),
    status varchar(9) NOT NULL DEFAULT 'Submitted',
    client_submission_id varchar(64),
    is_fixture smallint NOT NULL DEFAULT 0,
    created_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    updated_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    -- A retried submission (same form) never creates a second row. NULLs never conflict.
    CONSTRAINT uq_production_records_farmer_submission UNIQUE (farmer_id, client_submission_id),
    CONSTRAINT fk_production_records_farmer FOREIGN KEY (farmer_id) REFERENCES public.farmers (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_production_records_farm_profile FOREIGN KEY (farm_profile_id) REFERENCES public.farm_profiles (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_production_records_commodity FOREIGN KEY (commodity_id) REFERENCES public.commodities (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_production_records_quantity CHECK (quantity_kg > 0),
    CONSTRAINT chk_production_records_status CHECK (status IN ('Submitted', 'Verified', 'Rejected')),
    CONSTRAINT chk_production_records_is_fixture CHECK (is_fixture IN (0, 1))
);
-- Farmer screens (own records by month) and the future admin report (all farmers by month, commodity or farm).
CREATE INDEX idx_production_records_farmer_harvest ON public.production_records (farmer_id, harvest_date);
CREATE INDEX idx_production_records_harvest ON public.production_records (harvest_date);
CREATE INDEX idx_production_records_commodity_harvest ON public.production_records (commodity_id, harvest_date);
CREATE INDEX idx_production_records_farm_harvest ON public.production_records (farm_profile_id, harvest_date);
CREATE TRIGGER trg_production_records_updated_at BEFORE UPDATE ON public.production_records FOR EACH ROW EXECUTE FUNCTION public.agrireach_touch_updated_at();

