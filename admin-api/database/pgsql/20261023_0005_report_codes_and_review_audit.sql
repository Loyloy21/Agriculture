-- AgriReach: farmer-facing report codes (RSBSA reference + per-farmer sequence) and an audit trail of
-- admin-verified figure saves.
-- BACKWARD COMPATIBLE:
--   * New table public.farmer_report_sequences: one counter row per farmer. The server raises it inside
--     the report transaction while holding the row lock, so concurrent submissions get distinct numbers.
--     It only ever increases: an archived, deleted or RSBSA-corrected report never frees or reuses one.
--   * damage_reports.report_sequence (NULLable): the number given to a new report. Older reports keep
--     their existing report_code and have no sequence. UNIQUE (farmer_id, report_sequence) guards it.
--   * New table public.damage_report_verification_audit: one row per changed admin-verified save.
-- Nothing is dropped and no existing row is rewritten.
--
-- Apply with:   php scripts/pgsql-migrate.php --connection=supabase
-- Roll back:    database/pgsql/rollback/20261023_0005_report_codes_and_review_audit.down.sql

BEGIN;

CREATE TABLE public.farmer_report_sequences (
    farmer_id integer PRIMARY KEY,
    last_sequence integer NOT NULL DEFAULT 0,
    updated_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    CONSTRAINT fk_farmer_report_sequences_farmer FOREIGN KEY (farmer_id) REFERENCES public.farmers (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_farmer_report_sequences_nonnegative CHECK (last_sequence >= 0)
);
CREATE TRIGGER trg_farmer_report_sequences_updated_at BEFORE UPDATE ON public.farmer_report_sequences FOR EACH ROW EXECUTE FUNCTION public.agrireach_touch_updated_at();

ALTER TABLE public.damage_reports ADD COLUMN report_sequence integer;
ALTER TABLE public.damage_reports ADD CONSTRAINT chk_damage_reports_report_sequence CHECK (report_sequence >= 1);
-- NULL sequences (older reports) never conflict with each other.
ALTER TABLE public.damage_reports ADD CONSTRAINT uq_damage_reports_farmer_sequence UNIQUE (farmer_id, report_sequence);

-- Re-apply safety (e.g. after the rollback script): codes already issued in the new format keep their
-- number and the counters continue after them. On the first apply no such codes exist and nothing changes.
UPDATE public.damage_reports SET report_sequence = CAST(substring(report_code from '-([0-9]+)$') AS integer)
 WHERE report_sequence IS NULL AND report_code ~ '^[0-9]{2}-[0-9]{2}-[0-9]{2}-[0-9]{3}-[0-9]{6}-[0-9]+$';
INSERT INTO public.farmer_report_sequences (farmer_id, last_sequence)
SELECT farmer_id, MAX(report_sequence) FROM public.damage_reports WHERE report_sequence IS NOT NULL GROUP BY farmer_id;

CREATE TABLE public.damage_report_verification_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id integer NOT NULL,
    admin_id integer NOT NULL,
    verified_cause varchar(300),
    verified_summary varchar(255),
    review_notes text,
    report_status varchar(50) NOT NULL,
    created_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    CONSTRAINT fk_damage_verification_audit_report FOREIGN KEY (report_id) REFERENCES public.damage_reports (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_damage_verification_audit_admin FOREIGN KEY (admin_id) REFERENCES public.admins (id) ON UPDATE CASCADE
);
CREATE INDEX idx_damage_verification_audit_report ON public.damage_report_verification_audit (report_id);
CREATE INDEX fk_damage_verification_audit_admin ON public.damage_report_verification_audit (admin_id);

-- Same lockout as every other AgriReach table (PHP connects directly; the Supabase Data API gets nothing).
ALTER TABLE public.farmer_report_sequences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.damage_report_verification_audit ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.farmer_report_sequences, public.damage_report_verification_audit FROM anon;
        REVOKE ALL ON SEQUENCE public.damage_report_verification_audit_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.farmer_report_sequences, public.damage_report_verification_audit FROM authenticated;
        REVOKE ALL ON SEQUENCE public.damage_report_verification_audit_id_seq FROM authenticated;
    END IF;
END;
$$;

INSERT INTO public.agrireach_schema_migrations (version) VALUES ('20261023_0005_report_codes_and_review_audit');

COMMIT;
