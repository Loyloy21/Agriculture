-- AgriReach: single-admin replacement (invite -> recipient sets a password -> current admin transfers access).
-- BACKWARD COMPATIBLE:
--   * uq_admins_single_active: the database refuses a second admin with status 'active'. The migration fails
--     (and changes nothing) if more than one admin is active today.
--   * New table public.admin_replacement_invitations: one replacement process. Only a SHA-256 hash of the
--     emailed invitation token is stored; the recipient's own password hash is held here until the transfer
--     (it never grants access before then). uq_admin_replacement_open allows one Pending/Ready process at a time.
--   * New table public.admin_account_events: audit trail of invitations, transfers and sender changes, also used
--     as the rate-limit ledger (client addresses only as hashes; never tokens, passwords or email credentials).
-- No existing row is changed. Admin rows are never deleted by the application, so history keeps its references.
--
-- Apply with:   php scripts/pgsql-migrate.php --connection=supabase
-- Roll back:    database/pgsql/rollback/20261024_0008_admin_replacement.down.sql

BEGIN;

CREATE UNIQUE INDEX uq_admins_single_active ON public.admins (status) WHERE status = 'active';

CREATE TABLE public.admin_replacement_invitations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status varchar(9) NOT NULL DEFAULT 'Pending',
    full_name varchar(120) NOT NULL,
    -- Becomes the replacement's login username, hence the 60-character admin username limit.
    email extensions.citext NOT NULL,
    invited_by_admin_id integer,
    token_hash char(64),
    token_expires_at timestamp(0) without time zone,
    email_status varchar(9) NOT NULL DEFAULT 'Pending',
    email_failure_code varchar(80),
    send_count smallint NOT NULL DEFAULT 0,
    last_sent_at timestamp(0) without time zone,
    password_hash varchar(255),
    setup_completed_at timestamp(0) without time zone,
    ready_expires_at timestamp(0) without time zone,
    replacement_admin_id integer,
    closed_at timestamp(0) without time zone,
    created_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    updated_at timestamp(0) without time zone NOT NULL DEFAULT public.agrireach_local_now(),
    CONSTRAINT uq_admin_replacement_token UNIQUE (token_hash),
    CONSTRAINT fk_admin_replacement_inviter FOREIGN KEY (invited_by_admin_id) REFERENCES public.admins (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_admin_replacement_admin FOREIGN KEY (replacement_admin_id) REFERENCES public.admins (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_admin_replacement_status CHECK (status IN ('Pending', 'Ready', 'Completed', 'Cancelled', 'Expired')),
    CONSTRAINT chk_admin_replacement_email_status CHECK (email_status IN ('Pending', 'Sent', 'Simulated', 'Failed')),
    CONSTRAINT chk_admin_replacement_email_length CHECK (char_length(email) <= 60),
    CONSTRAINT chk_admin_replacement_send_count CHECK (send_count >= 0)
);
-- One open replacement process (Pending or Ready) at a time.
CREATE UNIQUE INDEX uq_admin_replacement_open ON public.admin_replacement_invitations ((status IN ('Pending', 'Ready'))) WHERE status IN ('Pending', 'Ready');
CREATE INDEX fk_admin_replacement_inviter ON public.admin_replacement_invitations (invited_by_admin_id);
CREATE INDEX fk_admin_replacement_admin ON public.admin_replacement_invitations (replacement_admin_id);
CREATE TRIGGER trg_admin_replacement_invitations_updated_at BEFORE UPDATE ON public.admin_replacement_invitations FOR EACH ROW EXECUTE FUNCTION public.agrireach_touch_updated_at();

CREATE TABLE public.admin_account_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type varchar(32) NOT NULL,
    actor_admin_id integer,
    subject_admin_id integer,
    invitation_id integer,
    detail varchar(255),
    ip_hash char(64),
    created_at_utc timestamp(0) without time zone NOT NULL,
    CONSTRAINT fk_admin_account_events_actor FOREIGN KEY (actor_admin_id) REFERENCES public.admins (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_admin_account_events_subject FOREIGN KEY (subject_admin_id) REFERENCES public.admins (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_admin_account_events_invitation FOREIGN KEY (invitation_id) REFERENCES public.admin_replacement_invitations (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_admin_account_events_type CHECK (event_type IN (
        'invitation_created', 'invitation_resent', 'invitation_send_failed', 'invitation_cancelled', 'invitation_expired',
        'invitation_viewed', 'invitation_rejected', 'setup_completed', 'transfer_completed', 'transfer_failed',
        'transfer_reauth_failed', 'notification_sent', 'notification_failed', 'sender_changed', 'sender_change_rejected',
        'recovery_password_reset', 'recovery_admin_activated'))
);
CREATE INDEX idx_admin_account_events_type_time ON public.admin_account_events (event_type, created_at_utc);
CREATE INDEX idx_admin_account_events_actor ON public.admin_account_events (actor_admin_id, created_at_utc);
CREATE INDEX idx_admin_account_events_ip ON public.admin_account_events (ip_hash, created_at_utc);
CREATE INDEX fk_admin_account_events_subject ON public.admin_account_events (subject_admin_id);
CREATE INDEX fk_admin_account_events_invitation ON public.admin_account_events (invitation_id);

-- Same lockout as every other AgriReach table (PHP connects directly; the Supabase Data API gets nothing).
ALTER TABLE public.admin_replacement_invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_account_events ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.admin_replacement_invitations, public.admin_account_events FROM anon;
        REVOKE ALL ON SEQUENCE public.admin_replacement_invitations_id_seq, public.admin_account_events_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.admin_replacement_invitations, public.admin_account_events FROM authenticated;
        REVOKE ALL ON SEQUENCE public.admin_replacement_invitations_id_seq, public.admin_account_events_id_seq FROM authenticated;
    END IF;
END;
$$;

