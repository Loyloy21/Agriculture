-- AgriReach: farmer Forgot Password (one-time emailed code). ADDITIVE ONLY: two new tables, no
-- change to any existing table, column, row, constraint, or function.
--
-- Apply with:
--   php scripts/pgsql-migrate.php --connection=supabase
-- (the runner skips versions already listed in agrireach_schema_migrations).
--
-- Every *_utc column is UTC, written by PHP with db_sql_utc_now(). The plaintext code is never
-- stored: code_verifier holds password_hash() of it, and reset_token_hash holds SHA-256 of the
-- one-time token issued after the code is verified.

BEGIN;

CREATE TABLE public.farmer_password_resets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id integer NOT NULL,
    code_verifier varchar(255) NOT NULL,
    failed_attempts smallint NOT NULL DEFAULT 0,
    expires_at_utc timestamp(0) without time zone NOT NULL,
    verified_at_utc timestamp(0) without time zone,
    reset_token_hash varchar(64),
    reset_token_expires_at_utc timestamp(0) without time zone,
    used_at_utc timestamp(0) without time zone,
    revoked_at_utc timestamp(0) without time zone,
    revoke_reason varchar(10),
    delivery_status varchar(9) NOT NULL DEFAULT 'Pending',
    delivery_failure_code varchar(80),
    created_at_utc timestamp(0) without time zone NOT NULL,
    CONSTRAINT uq_farmer_password_resets_token UNIQUE (reset_token_hash),
    CONSTRAINT fk_farmer_password_resets_farmer FOREIGN KEY (farmer_id) REFERENCES public.farmers (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_farmer_password_resets_attempts CHECK (failed_attempts >= 0),
    CONSTRAINT chk_farmer_password_resets_revoke_reason CHECK (revoke_reason IN ('superseded', 'attempts', 'completed')),
    CONSTRAINT chk_farmer_password_resets_delivery CHECK (delivery_status IN ('Pending', 'Sent', 'Failed', 'Simulated'))
);
CREATE INDEX idx_farmer_password_resets_farmer ON public.farmer_password_resets (farmer_id, created_at_utc);

-- Rate-limit ledger: one row per request / failed code / reset attempt. Emails and IP addresses are
-- stored only as SHA-256 hashes. Rows are written for unknown emails too, so limits never reveal
-- whether an account exists.
CREATE TABLE public.farmer_password_reset_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action varchar(13) NOT NULL,
    email_hash varchar(64),
    ip_hash varchar(64) NOT NULL,
    created_at_utc timestamp(0) without time zone NOT NULL,
    CONSTRAINT chk_farmer_password_reset_events_action CHECK (action IN ('request', 'verify_failed', 'reset'))
);
CREATE INDEX idx_farmer_password_reset_events_email ON public.farmer_password_reset_events (action, email_hash, created_at_utc);
CREATE INDEX idx_farmer_password_reset_events_ip ON public.farmer_password_reset_events (action, ip_hash, created_at_utc);
CREATE INDEX idx_farmer_password_reset_events_created ON public.farmer_password_reset_events (created_at_utc);

-- Same lockout as every other AgriReach table: PHP talks to Postgres directly, so the Supabase Data
-- API roles get nothing (RLS on with no policies, and no grants).
ALTER TABLE public.farmer_password_resets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.farmer_password_reset_events ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.farmer_password_resets, public.farmer_password_reset_events FROM anon;
        REVOKE ALL ON SEQUENCE public.farmer_password_resets_id_seq, public.farmer_password_reset_events_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.farmer_password_resets, public.farmer_password_reset_events FROM authenticated;
        REVOKE ALL ON SEQUENCE public.farmer_password_resets_id_seq, public.farmer_password_reset_events_id_seq FROM authenticated;
    END IF;
END;
$$;

INSERT INTO public.agrireach_schema_migrations (version) VALUES ('20261019_0002_farmer_password_resets');

COMMIT;
